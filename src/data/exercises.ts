export function getExerciseImageUrl(imagePath: string): string {
  if (imagePath.startsWith("http://") || imagePath.startsWith("https://")) {
    return imagePath;
  }
  if (imagePath.startsWith("/")) {
    if (typeof window !== "undefined" && window.location?.origin) {
      return `${window.location.origin}${imagePath}`;
    }
    return imagePath;
  }
  return `${EXERCISE_IMAGE_BASE}/${imagePath}`;
}

export function getYoutubeSearchUrl(query: string): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(
    `${query} exercise form`
  )}`;
}

export function getYoutubeEmbedUrl(videoId: string): string {
  return `https://www.youtube.com/embed/${videoId}`;
}

export function getExerciseVideoUrl(exercise: {
  nameEn: string;
  youtubeVideoId?: string;
}): string {
  if (exercise.youtubeVideoId) {
    return `https://www.youtube.com/watch?v=${exercise.youtubeVideoId}`;
  }
  return getYoutubeSearchUrl(exercise.nameEn);
}

export function canEmbedExerciseVideo(exercise: {
  youtubeVideoId?: string;
}): boolean {
  return Boolean(exercise.youtubeVideoId);
}

